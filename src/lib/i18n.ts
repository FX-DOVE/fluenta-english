export function categoryLabel(lang: Lang, category: string): string {
  const map: Record<string, string> = {
    General: "cat_general",
    Speaking: "cat_speaking",
    Grammar: "cat_grammar",
    Career: "cat_career",
    Listening: "cat_listening",
  };
  const key = map[category];
  return key ? t(lang, key) : category;
}

